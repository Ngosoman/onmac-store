const fallbackRemoteImage = 'https://images.unsplash.com/photo-1510812431401-41d2bd2722f3?auto=format&fit=crop&w=900&q=80';

function imageUrl(category, subcategory) {
  return remoteImagesBySeries[`${category}:${subcategory}`] || fallbackRemoteImage;
}

function formatPrice(amount) {
  return `$${amount.toFixed(2)}`;
}

let nextId = 1;

function createSeries({
  category,
  subcategory,
  brands,
  expressions,
  sizes,
  basePrice,
  step,
  note,
  tags,
  imageQuery,
}) {
  return brands.map((brand, index) => {
    const expression = expressions[index % expressions.length];
    const size = sizes[index % sizes.length];
    const combinedTags = [brand, category, subcategory, expression, ...tags].map((value) => String(value).toLowerCase());

    return {
      id: nextId++,
      name: `${brand} ${expression}`,
      brand,
      category,
      subcategory,
      size,
      price: formatPrice(basePrice + (index * step)),
      note,
      tags: combinedTags,
      image: imageUrl(category, subcategory),
    };
  });
}

